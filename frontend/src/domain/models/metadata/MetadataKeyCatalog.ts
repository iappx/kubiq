    public static describe(key: string): string {
        if (Object.prototype.hasOwnProperty.call(MetadataKeyCatalog.exactDescriptions, key)) {
            return MetadataKeyCatalog.exactDescriptions[key]
        }

        for (const [prefix, description] of MetadataKeyCatalog.prefixDescriptions) {
            if (key.startsWith(prefix)) {
                return description
            }
        }

        return ''
    }
